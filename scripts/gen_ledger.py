#!/usr/bin/env python3
"""Generate SYNTHETIC ledger history (seeded, deterministic) -> data/ledger_history.json.
Weeks are simulated with the real state machine in receipts/ledger.py so lanes in the history are what the rules would produce.
Scripted story: promotions are earned, one analyzer-core escape (wk9) demotes it to L3, one canary dip (wk7) demotes generator-templates."""
import random
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from receipts import ledger  # noqa: E402
from receipts.util import write_json  # noqa: E402

SEED = 2026
WEEKS = 12
START = date(2026, 8, 24)
LABEL = "SYNTHETIC: seeded simulation (seed %d) generated by scripts/gen_ledger.py; not measurements of any real team." % SEED
# area: (receipts/week, avg changed lines/receipt, canaries planted/week, base canary recall, base finding precision)
AREAS = {
    "analyzer-core":       (7, 120, 4, 0.93, 0.74),
    "generator-templates": (5, 150, 4, 0.92, 0.70),
    "generated-snapshots": (9, 400, 0, 1.00, 0.95),
    "tests":               (14, 90, 3, 0.94, 0.80),
    "docs":                (8, 40, 3, 0.95, 0.85),
    "runtime-serializer":  (3, 80, 4, 0.91, 0.66),
}
ESCAPES = {(9, "analyzer-core"): 1}
CANARY_OVERRIDE = {(7, "generator-templates"): (4, 1), (9, "analyzer-core"): (4, 3)}
REVIEW_MIN = {"L0": 2.0, "L1": 7.0, "L2": 18.0, "L3": 40.0}
TTM_H = {"L0": 2.0, "L1": 5.0, "L2": 14.0, "L3": 30.0}
READ_FRAC = {"L0": 0.01, "L1": 0.04, "L2": 0.14, "L3": 1.0}   # share of changed lines a human must read
ROUTED = {"L0": False, "L1": False, "L2": True, "L3": True}


def main():
    rng = random.Random(SEED)
    promo, demo, cold = ledger.params()
    cfgs = ledger.area_cfgs()
    weeks = [(START + timedelta(weeks=i)).isoformat() for i in range(WEEKS)]
    out = {"synthetic": True, "label": LABEL, "seed": SEED, "weeks": weeks, "baseline_human_only_review_min": 40, "baseline_note": "ASSUMPTION: a human-only full read costs ~40 min/PR; used only as a reference line", "areas": {}}
    for area, (n0, lines0, planted0, recall0, prec0) in AREAS.items():
        st = ledger.new_state(cfgs[area], cold)
        recs = []
        for w in range(1, WEEKS + 1):
            n = max(1, round(n0 * rng.uniform(0.8, 1.2)))
            esc = ESCAPES.get((w, area), 0)
            if (w, area) in CANARY_OVERRIDE:
                planted, caught = CANARY_OVERRIDE[(w, area)]
            else:
                planted = planted0
                caught = planted   # background weeks: the reviewer catches what the drill plants; misses are scripted (CANARY_OVERRIDE)
            lane = st["lane"]                      # lane in effect during the week (before this week's step)
            lines = round(n * lines0 * rng.uniform(0.85, 1.15))
            findings = max(0, round(n * rng.uniform(0.6, 1.4))) if planted0 or area == "docs" else 0
            accepted = sum(1 for _ in range(findings) if rng.random() < prec0)
            minutes = REVIEW_MIN[lane] * rng.uniform(0.85, 1.15)
            ttm = TTM_H[lane] * rng.uniform(0.8, 1.25)
            reverts = esc + int(n * 0.02 + rng.random())   # flat ~2% background revert rate (low-variance rounding)
            rec = {"receipts": n, "escapes": esc, "canary_planted": planted, "canary_caught": caught,
                   "changed_lines": lines, "routed_lines": round(lines * READ_FRAC[lane]),
                   "routed_changes": n if ROUTED[lane] else 0,
                   "findings": findings, "findings_accepted": accepted, "reverts": reverts,
                   "median_review_min": round(minutes, 1), "median_ttm_h": round(ttm, 1)}
            ledger.step(st, w, rec, cfgs[area], promo, demo)
            recs.append(rec)
        out["areas"][area] = recs
    write_json(ROOT / "data" / "ledger_history.json", out)
    state = ledger.build(write=True, applies_to_routing=False)
    ledger.print_summary(state)


if __name__ == "__main__":
    main()
